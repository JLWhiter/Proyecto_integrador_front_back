CREATE DATABASE IF NOT EXISTS proyecto CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE proyecto;
-- Fresh installation only. For an existing database run migrations/001_integridad.sql.
DROP PROCEDURE IF EXISTS instalar_techzone;
DELIMITER $$
CREATE PROCEDURE instalar_techzone()
principal: BEGIN
IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema=DATABASE() AND table_name IN ('producto','venta','parametro','cliente','usuario','persona','tipo_documento','medio_pago','detalle_venta','secuencia_documento','movimiento_stock')) THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='La base ya contiene tablas: utilice la migracion, no el instalador';
END IF;

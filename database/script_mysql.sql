    cantidad INT NOT NULL,
    stock_resultante INT NOT NULL CHECK (stock_resultante >= 0),
    motivo VARCHAR(255) NOT NULL,
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (id_producto) REFERENCES producto(id_producto)
);
INSERT INTO movimiento_stock(id_producto,cantidad,stock_resultante,motivo)
SELECT id_producto,stock,stock,'SALDO_INICIAL' FROM producto;
UPDATE venta v JOIN cliente c ON c.id_cliente=v.id_cliente SET v.nombre_cliente=CONCAT(c.nombre,' ',c.apellido);
UPDATE detalle_venta d JOIN producto p ON p.id_producto=d.id_producto SET d.nombre_producto=p.nombre, d.igv=ROUND(d.subtotal*18/118,2);

END$$

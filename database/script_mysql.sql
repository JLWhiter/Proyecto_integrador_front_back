-- ============================================================================
--  VISTA
--  "cliente" y "apellido" provienen ahora de la tabla cliente (el comprador).
--  "vendedor" se sigue obteniendo de persona a traves de venta.id_persona.
-- ============================================================================

CREATE OR REPLACE VIEW historial_compras AS
SELECT
    v.id_venta,
    v.fecha_emision,
    td.nombre AS tipo_documento,
    v.nombre_cliente AS cliente,
    cl.apellido,
    dv.nombre_producto AS producto,
    dv.cantidad,
    dv.precio_unitario,
    dv.subtotal,
    mp.descripcion AS medio_pago,
    pe.nombre AS vendedor
FROM venta v
INNER JOIN cliente cl       ON v.id_cliente = cl.id_cliente
LEFT JOIN persona pe       ON v.id_persona = pe.id_persona
INNER JOIN tipo_documento td ON v.id_tipo_documento = td.id_documento
INNER JOIN medio_pago mp    ON v.id_medio_pago = mp.id_medio_pago
INNER JOIN detalle_venta dv ON v.id_venta = dv.id_venta
INNER JOIN producto pr      ON dv.id_producto = pr.id_producto;


CREATE TABLE secuencia_documento (serie VARCHAR(4) PRIMARY KEY, ultimo BIGINT NOT NULL CHECK (ultimo >= 0));

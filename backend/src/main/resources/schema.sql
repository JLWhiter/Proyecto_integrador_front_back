CREATE TABLE parametro (
    id_parametro VARCHAR(30)  NOT NULL,
    valor        VARCHAR(50)  NOT NULL,
    descripcion  VARCHAR(100) NOT NULL,
    PRIMARY KEY (id_parametro)
);

CREATE TABLE tipo_documento (
    id_documento VARCHAR(25)  NOT NULL,
    nombre      VARCHAR(50)  NOT NULL,
    PRIMARY KEY (id_documento)
);

CREATE TABLE medio_pago (
    id_medio_pago VARCHAR(10)  NOT NULL,
    descripcion   VARCHAR(100) NOT NULL,
    PRIMARY KEY (id_medio_pago)
);

CREATE TABLE persona (
    id_persona       VARCHAR(25) NOT NULL,
    nombre           VARCHAR(50) NOT NULL,
    apellido         VARCHAR(50) NOT NULL,
    fecha_nacimiento DATE,
    correo           VARCHAR(100),
    telefono         VARCHAR(9),
    usuario          VARCHAR(50),
    PRIMARY KEY (id_persona)
);

-- id_usuario: GENERATED BY DEFAULT AS IDENTITY (Postgres) -> GENERATED BY DEFAULT AS IDENTITY (MySQL)
CREATE TABLE usuario (
    id_usuario INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    usuario    VARCHAR(50)  NOT NULL UNIQUE,
    contrasena VARCHAR(255) NOT NULL,
    id_persona VARCHAR(25)  NOT NULL,
    PRIMARY KEY (id_usuario),
    CONSTRAINT fk_usuario_persona FOREIGN KEY (id_persona)
        REFERENCES persona (id_persona)
);

-- El COMPRADOR. Antes de esta version la tabla no tenia ninguna relacion:
-- se relacionaba con persona() a traves de venta.id_persona.
CREATE TABLE cliente (
    id_cliente VARCHAR(20)  NOT NULL,
    nombre     VARCHAR(50)  NOT NULL,
    apellido   VARCHAR(50)  NOT NULL,
    telefono   VARCHAR(15),
    contrasena VARCHAR(255) NOT NULL,
    correo     VARCHAR(100),
    UNIQUE (correo),
    PRIMARY KEY (id_cliente)
);

CREATE TABLE producto (
    id_producto INT            NOT NULL,
    nombre      VARCHAR(100)   NOT NULL,
    stock       INT            NOT NULL CHECK (stock >= 0),
    precio      DECIMAL(10, 2) NOT NULL CHECK (precio >= 0),
    categoria   VARCHAR(80)    NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id_producto)
);

-- id_cliente = comprador  |  id_persona = vendedor/empleado que proceso la venta
CREATE TABLE venta (
    id_venta          VARCHAR(36) NOT NULL,
    id_cliente        VARCHAR(20) NOT NULL,
    id_persona        VARCHAR(25),
    id_tipo_documento VARCHAR(25) NOT NULL,
    numero_documento  VARCHAR(36) NOT NULL UNIQUE,
    doc_cliente VARCHAR(11),
    razon_social VARCHAR(200),
    direccion_cliente VARCHAR(255),
    nombre_cliente VARCHAR(200) NOT NULL DEFAULT '',
    igv_porcentaje DECIMAL(5,2) NOT NULL DEFAULT 18 CHECK (igv_porcentaje >= 0),
    id_medio_pago     VARCHAR(10) NOT NULL,
    fecha_emision     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id_venta),
    CONSTRAINT fk_venta_cliente FOREIGN KEY (id_cliente)
        REFERENCES cliente (id_cliente),
    CONSTRAINT fk_venta_persona FOREIGN KEY (id_persona)
        REFERENCES persona (id_persona),
    CONSTRAINT fk_venta_tipo_documento FOREIGN KEY (id_tipo_documento)
        REFERENCES tipo_documento (id_documento),
    CONSTRAINT fk_venta_medio_pago FOREIGN KEY (id_medio_pago)
        REFERENCES medio_pago (id_medio_pago)
);

-- id_detalle: GENERATED BY DEFAULT AS IDENTITY (Postgres) -> GENERATED BY DEFAULT AS IDENTITY (MySQL)
CREATE TABLE detalle_venta (
    id_detalle      INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_venta        VARCHAR(36)    NOT NULL,
    id_producto     INT            NOT NULL,
    cantidad        INT            NOT NULL CHECK (cantidad > 0),
    precio_unitario DECIMAL(10, 2) NOT NULL CHECK (precio_unitario >= 0),
    subtotal        DECIMAL(10, 2) NOT NULL CHECK (subtotal >= 0),
    nombre_producto VARCHAR(100) NOT NULL DEFAULT '',
    igv DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (igv >= 0),
    PRIMARY KEY (id_detalle),
    CONSTRAINT fk_detalle_venta FOREIGN KEY (id_venta)
        REFERENCES venta (id_venta),
    CONSTRAINT fk_detalle_producto FOREIGN KEY (id_producto)
        REFERENCES producto (id_producto)
);


CREATE TABLE secuencia_documento (serie VARCHAR(4) PRIMARY KEY, ultimo BIGINT NOT NULL CHECK (ultimo >= 0));
CREATE TABLE movimiento_stock (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id_producto INT NOT NULL REFERENCES producto(id_producto), cantidad INT NOT NULL, stock_resultante INT NOT NULL CHECK(stock_resultante >= 0), motivo VARCHAR(255) NOT NULL, fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
